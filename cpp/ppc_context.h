// Offset from `base` for guest effective address `ea`. Physical memory is
// visible through three views that alias on hardware: 0xA0000000 (64 KiB
// pages), 0xC0000000 (16 MiB pages) and 0xE0000000 (4 KiB pages, one page
// ahead: 0xE0000000 + x is physical x + 0x1000). Wasm can't map one memory at
// several addresses, so physical memory lives once, at 0xA0000000 + physical
// address, and the other two views are folded onto it. Every access goes through
// runtime-core's per-1 MiB offset table (memory::skyrt_ea_offset, which starts out
// as memory::fold_view and is what the runtime's own accesses use): a load and an
// add, cheaper than comparing and selecting, and it lets the runtime place guest
// memory anywhere in linear memory, 1 MiB at a time.
extern "C" const int32_t skyrt_ea_offset[4096];

//
// On Apple hosts guest memory is stored at its own addresses instead (runtime-core's
// memory::DIRECT, which this must match: guest-sys checks), the 16 MiB view mapped a second
// time, and there is nothing to look up.
#if defined(__APPLE__)
#define SKYRT_DIRECT_EA 1
#else
#define SKYRT_DIRECT_EA 0
#endif

static inline __attribute__((always_inline)) uint32_t skyrt_ea(uint32_t ea)
{
#if SKYRT_DIRECT_EA
    return ea;
#else
    return ea + (uint32_t)skyrt_ea_offset[ea >> 20];
#endif
}

#define PPC_EA(x) (base + skyrt_ea((uint32_t)(x)))

// One byte per 4 KiB page of the guest address space, cleared to 0 when a store
// may have changed the page (runtime-core's dirty module, which sets it back to
// 1 when the renderer consumes the mark, checking every address a physical page
// is visible at). Indexing by guest address keeps the mark to a shift and a byte
// store with no branch: on wasm, recompiled code is mostly memory accesses, and
// the code size is what Safari's memory use follows. The mark follows the data:
// the renderer consumes a mark before reading the page, so a store it misses
// leaves the page marked for next time. Plain byte stores suffice: the renderer
// only reads memory after the guest published it through the ring buffer, which
// orders everything before.
extern "C" uint8_t skyrt_written[];

static inline __attribute__((always_inline)) void skyrt_mark_written(uint32_t ea, uint32_t size)
{
    ((volatile uint8_t*)skyrt_written)[ea >> 12] = 0;
    if (size > 1)
        ((volatile uint8_t*)skyrt_written)[(ea + size - 1) >> 12] = 0;
}

#define PPC_MARK_WRITTEN(x, size) skyrt_mark_written((uint32_t)(x), (size))

// Memory barriers. The guest's lock-free code relies on them: a lock is released or an object
// published by "lwsync; stw", and without the barrier an ARM core may make that store visible
// before the writes it guards (Skyrim crashed on iPhones loading a new game, calling through a
// half-written object). x86 keeps stores in order and the guest's atomics (stwcx.) are full
// barriers already, so there they cost nothing; wasm builds keep the upstream behaviour.
// sync orders everything; lwsync everything but stores before later loads (acquire+release);
// eieio stores to device memory (release).
#if defined(__aarch64__) || defined(_M_ARM64)
#define PPC_SYNC() __atomic_thread_fence(__ATOMIC_SEQ_CST)
#define PPC_LWSYNC() __atomic_thread_fence(__ATOMIC_ACQ_REL)
#define PPC_EIEIO() __atomic_thread_fence(__ATOMIC_RELEASE)
#else
#define PPC_SYNC() ((void)0)
#define PPC_LWSYNC() ((void)0)
#define PPC_EIEIO() ((void)0)
#endif

// Load-reserve / store-conditional. On PowerPC a stwcx. fails if anything stored to the
// reservation granule since the lwarx; comparing the value alone (a compare-and-swap) lets
// another thread pop and push the same node in between unnoticed (ABA), and a lock-free list
// or heap pool then hands one node out twice. Skyrim's job lists ended up with cycles that
// way, a thread spinning forever in a list walk. Each conditional store therefore also bumps a
// version in a table indexed by address (odd while the store is in progress), and the store
// succeeds only if the version is still the one its load saw. Plain stores don't bump it: the
// guest's lock-free code updates shared words only with conditional stores. Distinct addresses
// may share a slot; that only costs a retry.
#define SKYRT_RESV_SLOTS 4096u

struct alignas(64) SkyrtResvSlot
{
    uint64_t version;
};

inline SkyrtResvSlot skyrt_resv[SKYRT_RESV_SLOTS];
// The thread's reservation: its slot and the version seen (1 = none; versions start even).
inline thread_local uint32_t skyrt_resv_slot_held;
inline thread_local uint64_t skyrt_resv_version = 1;

static inline __attribute__((always_inline)) uint32_t skyrt_resv_slot(uint32_t ea)
{
    return ((ea >> 2) * 0x9E3779B1u) >> (32 - 12);
}

static inline __attribute__((always_inline)) void skyrt_reserve(uint32_t ea)
{
    uint32_t slot = skyrt_resv_slot(ea);
    skyrt_resv_slot_held = slot;
    skyrt_resv_version = __atomic_load_n(&skyrt_resv[slot].version, __ATOMIC_ACQUIRE);
}

// Takes the slot for a conditional store to `ea` if the thread's reservation is intact.
static inline __attribute__((always_inline)) bool skyrt_resv_lock(uint32_t ea, uint64_t* version)
{
    uint64_t v = skyrt_resv_version;
    skyrt_resv_version = 1;
    uint32_t slot = skyrt_resv_slot(ea);
    if ((v & 1) != 0 || slot != skyrt_resv_slot_held)
        return false;
    *version = v;
    return __atomic_compare_exchange_n(&skyrt_resv[slot].version, &v, v + 1, false, __ATOMIC_ACQ_REL,
        __ATOMIC_RELAXED);
}

static inline __attribute__((always_inline)) void skyrt_resv_unlock(uint32_t ea, uint64_t version)
{
    __atomic_store_n(&skyrt_resv[skyrt_resv_slot(ea)].version, version + 2, __ATOMIC_RELEASE);
}

static inline __attribute__((always_inline)) uint32_t skyrt_lwarx(volatile uint32_t* p, uint32_t ea)
{
    skyrt_reserve(ea);
    return __atomic_load_n(p, __ATOMIC_SEQ_CST);
}

static inline __attribute__((always_inline)) uint64_t skyrt_ldarx(volatile uint64_t* p, uint32_t ea)
{
    skyrt_reserve(ea);
    return __atomic_load_n(p, __ATOMIC_SEQ_CST);
}

// `expected` and `value` are as stored (big-endian).
static inline __attribute__((always_inline)) bool skyrt_stwcx(volatile uint32_t* p, uint32_t ea, uint32_t expected,
    uint32_t value)
{
    uint64_t version;
    if (!skyrt_resv_lock(ea, &version))
        return false;
    bool stored = __atomic_compare_exchange_n(p, &expected, value, false, __ATOMIC_SEQ_CST, __ATOMIC_SEQ_CST);
    skyrt_resv_unlock(ea, version);
    return stored;
}

static inline __attribute__((always_inline)) bool skyrt_stdcx(volatile uint64_t* p, uint32_t ea, uint64_t expected,
    uint64_t value)
{
    uint64_t version;
    if (!skyrt_resv_lock(ea, &version))
        return false;
    bool stored = __atomic_compare_exchange_n(p, &expected, value, false, __ATOMIC_SEQ_CST, __ATOMIC_SEQ_CST);
    skyrt_resv_unlock(ea, version);
    return stored;
}

#define PPC_LWARX(x) skyrt_lwarx((volatile uint32_t*)PPC_EA(x), (uint32_t)(x))
#define PPC_LDARX(x) skyrt_ldarx((volatile uint64_t*)PPC_EA(x), (uint32_t)(x))
#define PPC_STWCX(x, expected, value) skyrt_stwcx((volatile uint32_t*)PPC_EA(x), (uint32_t)(x), (expected), (value))
#define PPC_STDCX(x, expected, value) skyrt_stdcx((volatile uint64_t*)PPC_EA(x), (uint32_t)(x), (expected), (value))

// Xenos half floats for vpkd3d128/vupkd3d128 (the skyrt XenonRecomp patch
// emits calls to these). Ported from Xenia's float_to_xenos_half /
// xenos_half_to_float (BSD): the extended range replaces infinity and NaN,
// denormals flush to zero and packing truncates, as vpkd3d128 does.
static inline uint16_t skyrt_float_to_xenos_half(float value)
{
    uint32_t bits;
    __builtin_memcpy(&bits, &value, 4);
    uint32_t abs_bits = bits & 0x7FFFFFFFu;
    uint32_t result;
    if (abs_bits >= 0x47FFE000u)
        result = 0x7FFFu; // saturate (also NaN)
    else if (abs_bits < 0x38800000u)
        result = 0u; // below the smallest normal half
    else
        result = ((abs_bits + 0xC8000000u) >> 13) & 0x7FFFu;
    return uint16_t(result | ((bits & 0x80000000u) >> 16));
}

static inline float skyrt_xenos_half_to_float(uint16_t value)
{
    uint32_t mantissa = value & 0x3FFu;
    uint32_t exponent = (value >> 10) & 0x1Fu;
    if (exponent == 0)
    {
        mantissa = 0;
        exponent = uint32_t(-112);
    }
    uint32_t bits = (uint32_t(value & 0x8000u) << 16) | ((exponent + 112u) << 23) | (mantissa << 13);
    float result;
    __builtin_memcpy(&result, &bits, 4);
    return result;
}

// Debug check (native, guest-sys built with SKYRT_CHECK_FRAMES=1): reports scalar
// accesses that straddle two 1 MiB frames that aren't adjacent in linear memory,
// which the compact layout would split wrongly (runtime-core logs them).
#ifdef SKYRT_CHECK_FRAMES_ENABLED
extern "C" void skyrt_frame_crossing(uint32_t ea, uint32_t size);
static inline void skyrt_check_frames(uint32_t ea, uint32_t size)
{
    if ((ea & 0xFFFFFu) + size > 0x100000u && skyrt_ea(ea + size - 1) != skyrt_ea(ea) + size - 1)
        skyrt_frame_crossing(ea, size);
}
#define SKYRT_CHECK_FRAMES(x, size) skyrt_check_frames((uint32_t)(x), (size))
#else
#define SKYRT_CHECK_FRAMES(x, size) ((void)0)
#endif

#if defined(__wasm_simd128__)
#include <wasm_simd128.h>
// Wasm has no byte swap instruction: a 64-bit one expands to ~40 scalar instructions,
// a shuffle to three.
static inline __attribute__((always_inline)) uint64_t skyrt_bswap64(uint64_t x)
{
    v128_t v = wasm_i8x16_swizzle(wasm_i64x2_splat((int64_t)x),
                                  wasm_i8x16_const(7, 6, 5, 4, 3, 2, 1, 0, 15, 14, 13, 12, 11, 10, 9, 8));
    return (uint64_t)wasm_i64x2_extract_lane(v, 0);
}
#else
#define skyrt_bswap64 __builtin_bswap64
#endif

